// content/scripts/build-keypoints.ts — content:keypoints (GC-09 / GC-15d machinery)
//
// Emits supabase/functions/grade-feynman/key-points.json: the canonical, concept-keyed set of
// Feynman key points the edge grader loads at runtime. The grader NEVER trusts the client for what
// "the right points" are — it loads this bundled file (see supabase/functions/grade-feynman/index.ts)
// and validates the model's covered/missing point IDs against it.
//
// Why a generated artifact instead of a DB read: the edge function must resolve key points before
// any Anthropic call, deterministically, with no network round-trip and no dependency on the (RLS'd)
// content tables. The JSON is derived PURELY from the same authored catalog the lesson concept cards
// render from (content/src via loadCatalog), so the key-point IDs are byte-identical to what the app
// shows the learner in explain-back (GC-15d round-trip). The zod layer already enforces that the
// lesson's explainBack.keyPointIds are a subset of the concept card's keyPoints, so this file is the
// third leg of that same triangle: concept card -> explain-back -> grader, all sharing one ID set.
//
// Determinism: concepts are sorted by id, key points keep authored order (order is meaningful — it is
// the order shown in the concept card), and every value is hashed with a canonical (key-sorted) JSON
// pass. Re-running with unchanged content reproduces the same file byte-for-byte, so `content:keypoints`
// is safe to run in the bundle chain and diff in CI. A conceptId that appears on two lessons with
// DIFFERENT key points is a hard error (the grader could not resolve a single canonical set).

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { loadCatalog } from './lib/load-catalog';
import type { KeyPoint } from '../schema/types';

const OUT_DIR = resolve(__dirname, '../../supabase/functions/grade-feynman');
const OUT_FILE = join(OUT_DIR, 'key-points.json');

/** Recursively sort object keys so the hash is independent of property insertion order. */
function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value !== null && typeof value === 'object') {
    const source = value as Record<string, unknown>;
    const sorted: Record<string, unknown> = {};
    for (const key of Object.keys(source).sort()) sorted[key] = canonicalize(source[key]);
    return sorted;
  }
  return value;
}

function sha256(value: unknown): string {
  return createHash('sha256').update(JSON.stringify(canonicalize(value)), 'utf8').digest('hex');
}

export interface ConceptKeyPoints {
  keyPoints: { id: string; text: string }[];
  hash: string;
}

export interface KeyPointsFile {
  note: string;
  contentVersion: string;
  concepts: Record<string, ConceptKeyPoints>;
}

/** Build the concept-keyed key-points map from a set of authored concept cards. Pure + testable. */
export function buildKeyPoints(
  concepts: { conceptId: string; keyPoints: KeyPoint[] }[],
): KeyPointsFile {
  const map: Record<string, ConceptKeyPoints> = {};
  for (const concept of [...concepts].sort((a, b) => (a.conceptId < b.conceptId ? -1 : a.conceptId > b.conceptId ? 1 : 0))) {
    const keyPoints = concept.keyPoints.map((kp) => ({ id: kp.id, text: kp.text }));
    const existing = map[concept.conceptId];
    if (existing !== undefined) {
      // Same conceptId on two lessons is fine ONLY if the key points are byte-identical; otherwise
      // the grader has no single canonical set to validate against.
      if (existing.hash !== sha256(keyPoints)) {
        throw new Error(
          `conceptId "${concept.conceptId}" has conflicting key points across lessons — the Feynman ` +
            `grader needs one canonical set per concept (fix the content or split the conceptId)`,
        );
      }
      continue;
    }
    map[concept.conceptId] = { keyPoints, hash: sha256(keyPoints) };
  }
  return {
    note: 'GENERATED by content/scripts/build-keypoints.ts (npm run content:keypoints). Do not hand-edit.',
    contentVersion: sha256(map),
    concepts: map,
  };
}

async function main(): Promise<void> {
  const { catalog, loadErrors } = await loadCatalog();
  if (loadErrors.length > 0) {
    for (const { file, error } of loadErrors) console.error(`load error ${file}: ${error}`);
    throw new Error(`content:keypoints — ${loadErrors.length} module(s) failed to load`);
  }
  const concepts = catalog.lessons.map((lesson) => ({
    conceptId: lesson.concept.conceptId,
    keyPoints: lesson.concept.keyPoints,
  }));
  const file = buildKeyPoints(concepts);
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, `${JSON.stringify(file, null, 2)}\n`);
  console.error(
    `content:keypoints -> ${OUT_FILE} (${Object.keys(file.concepts).length} concepts, version ${file.contentVersion.slice(0, 12)})`,
  );
}

if (require.main === module) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  });
}
